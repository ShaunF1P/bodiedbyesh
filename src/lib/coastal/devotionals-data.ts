/**
 * Fetch devotional by day number (1 - 14)
 */
export function getDevotionalByDay(dayNumber: number): FaithDevotional {
  const normalizedDay = Math.max(1, Math.min(14, Math.floor(dayNumber)));
  const match = DEVOTIONALS_DATA.find((d) => d.day_number === normalizedDay);
  return match || DEVOTIONALS_DATA[0];
}

/**
 * Deterministically compute current devotional based on date
 */
export function getDevotionalForDate(dateInput: Date | string = new Date()): FaithDevotional {
  const d = typeof dateInput === "string" ? new Date(dateInput) : dateInput;
  const startOfYear = new Date(d.getFullYear(), 0, 0);
  const diff = d.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const dayIndex = (dayOfYear % DEVOTIONALS_DATA.length) + 1;
  return getDevotionalByDay(dayIndex);
}

/**
 * Fetch all 14 devotionals in sequence
 */
export function getAllDevotionals(): FaithDevotional[] {
  return [...DEVOTIONALS_DATA];
}

/**
 * Default initial devotional (Day 1)
 */
export function getDefaultDevotional(): FaithDevotional {
  return DEVOTIONALS_DATA[0];
}
